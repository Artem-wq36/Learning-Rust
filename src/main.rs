fn main() {
    println!("/////////////////////////////////////////////////////////////");
    no1();
    no2();
    no3();
    no4();
}

fn no1() {

    let mut count = 0;

    loop {

        count += 1; // Щоразу, коли цикл виконується, лічильник збільшується на 1
        println!("Loop: {}", count); // Loop: 10

        if count == 10 { // Коли досягається значення 10, цикл зупиняється.
            break count; // Цикл зупиняєтсья і повертає число 10
        }
    };
    println!("/////////////////////////////////////////////////////////////");
}

fn no2() {
    let mut number = 0;

    while number <= 10 {

        if number == 5 { // Якщо number дорівнює 5, додає до нього 1, пропускає решту команд поточної ітерації та переходить до наступної ітерації циклу.
            number += 1;
            continue;
        }

        println!("While: {}", number); // Виводяться всі числа від 1 до 10 крім 5
        number += 1;
    }
    println!("/////////////////////////////////////////////////////////////");
}

fn no3() {
    for num in 1..=10 {
        if num % 2 == 0 { // Якщо число парне
            continue; // Пропускаємо ітерацію
        }

        if num == 9 { // Якщо число дорівнює 9
            break; // Зупиняємо цикл
        }
        println!("For: {}", num); // Непарні числа до 9 виводяться на екран
    }
    println!("/////////////////////////////////////////////////////////////");
}

fn no4() {
    for i in (1..=5).rev().step_by(2) {
        println!("Number: {}", i);
    }
    println!("/////////////////////////////////////////////////////////////");
}

// Головна функція
fn main() {
    no1();
    no2();
    no3();
}

// Перша додаткова функція (Змінні і присвоєння)
fn no1() { // Функція і початок тіла функції
    
    let mut x = "Початкове значення змінної"; // Оголошення змінної і дозвіл на зміну значень змінної
    
    println!("Було: {}", x); // Макрос, який виводить текст у консоль і переходить на новий рядок
    
    x = "Нове значення змінної"; // Присвоєння нового значення змінній x
    
    println!("Стало: {}", x);
} // Кінець тіла функції


// Друга додаткова функція (Типи даних)
fn no2() {
    let temperature: i32 = -43; // i32 - може зберігати додатні та від'ємні цілі числа
    let age: u32 = 28; // u32 - може зберігати лише нуль або додатні цілі числа
    let price: f64 = 25.99; // f64 - використовується для зберігання чисел, що містять один або декілька знаків підрядка (плаваюча крапка)
    let name: &str = "Maksym";
    let rust: bool = true;
    let symbol: char = 'A';

    println!("Температура (i32): {}", temperature);
    println!("Вік (u32): {}", age);
    println!("Ціна (f64): {}", price);
    println!("Ім'я (&str): {}", name);
    println!("Цікаво вивчати Rust? (bool): {}", rust);
    println!("Символ (char): {}", symbol);
}

// Третя додаткова функція (Константа)
fn no3() {
    const PI: f64 = 3.14;
    println!("Число ПІ (const): {}", PI);
}